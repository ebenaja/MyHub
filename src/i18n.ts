const idToEn = new Map<string, string>();
const enToId = new Map<string, string>();
for (const [id, en] of pairs) {
  idToEn.set(id, en);
  enToId.set(en, id);
}

export function translate(language: Language, text: string): string {
  if (language === "id") return enToId.get(text) ?? text;
  return idToEn.get(text) ?? text;
}

export function translateCategory(language: Language, value: string): string {
  return translate(language, value);
}
